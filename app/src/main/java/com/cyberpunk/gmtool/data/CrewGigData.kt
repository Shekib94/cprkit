/** یک Check با DV مشخص و نتیجه‌ی روشن. */
data class GigCheck(
    val dv: String,
    val skill: String,
    val result: String,
    /** راه جایگزین برای گروهی که آن مهارت را ندارد. */
    val alt: String = ""
)

/** یک بخش از سناریو. */
data class GigSection(
    val title: String,
    val body: String,
    val checks: List<GigCheck> = emptyList(),
    /** جعبه‌ی هشدار/نکته‌ی اجرایی برای GM. */
    val gmTip: String = ""
)

/** معماری NET یک مکان + راه دور زدنش بدون Netrunner. */
