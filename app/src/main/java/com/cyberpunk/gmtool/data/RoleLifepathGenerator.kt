        2 -> "فیکسرهای رقیب که تلاش می‌کنند مشتریانت را بدزدند."
        3 -> "مدیران شرکتی (می‌خواهند تو منحصراً فقط برای آن‌ها کار کنی)."
        4 -> "دشمنِ یکی از مشتریان سابق که می‌خواهد «ردپاهای باقی‌مانده» (یعنی تو) را پاک کند."
        5 -> "یک مشتری قدیمی که فکر می‌کند سرش کلاه گذاشته‌ای."
        6 -> "یک فیکسر رقیب که سرِ منابع و قطعات با تو در جنگ است."
        else -> "نامشخص"
    }
    story += "🎯 دشمن خونی: $gunning"

    return story
}
// --- مسیر زندگی اختصاصی نومَد (Nomad) ---
fun generateNomad(): String {
    // ۱. اندازه قبیله (Pack) شما چقدر است؟ (1d6)
    val size = when (DiceSource.rollOne(6, "Lifepath — جدول d6")) {
        1 -> "یک خانواده یا قبیله‌ی گسترده‌ی منفرد."
        2 -> "چندین دوجین عضو (حدود ۲۰ تا ۵۰ نفر)."
        3 -> "چهل یا پنجاه عضو."
        4 -> "صد عضو یا بیشتر."
        5 -> "یک «خانواده خونی» کامل (شامل صدها عضو)."
        6 -> "یک «خانواده متحد» (متشکل از چندین خانواده خونی متفاوت)."
        else -> "نامشخص"
    }

    var story = "⛺ اندازه قبیله: $size\n"

    // ۲. قبیله شما زمینی، هوایی یا دریایی است؟ (انتخاب رندوم)
    val baseType = listOf("Land", "Air", "Sea").random()

    // ۳. بر اساس نوع قبیله، کارشان چیست؟
    val packJob = when (baseType) {
        "Land" -> {
            when (DiceSource.rollOne(10, "Lifepath — جدول d10")) {
                1 -> "گُ‌گنگ (Gogang - گنگ موتورسوار خشن)"
                2 -> "حمل و نقل مسافر"
                3 -> "کاروان‌های آموزشی / مدارس سیار (Chautauqua)"
                4 -> "کارناوال و نمایش‌های سیار"
                5 -> "کشاورزان مهاجر"
                6 -> "حمل و نقل بار و محموله"
                7 -> "محافظت از محموله‌ها (Shipment protection)"
                8 -> "قاچاق کالا (Smuggling)"
                9 -> "ارتش مزدوران (Mercenary army)"
                10 -> "گروه‌های کارگر ساختمانی"
                else -> "نامشخص"
            }
        }
        "Air" -> {
            when (DiceSource.rollOne(6, "Lifepath — جدول d6")) {
                1 -> "دزدی هوایی (Air piracy)"
                2 -> "حمل و نقل بار هوایی"
                3 -> "حمل و نقل مسافر"
                4 -> "محافظت از هواگردها"
                5 -> "قاچاق هوایی (Smuggling)"
                6 -> "پشتیبانی هوایی رزمی (Combat support)"
                else -> "نامشخص"
            }
        }
        else -> { // Sea
            when (DiceSource.rollOne(6, "Lifepath — جدول d6")) {
                1 -> "دزدی دریایی (Piracy)"
                2 -> "حمل و نقل بار دریایی"
                3 -> "حمل و نقل مسافر"
                4 -> "قاچاق دریایی (Smuggling)"
                5 -> "پشتیبانی رزمی دریایی (Combat support)"
                6 -> "جنگ‌افزارهای زیردریایی (Submarine warfare)"
                else -> "نامشخص"
            }
        }
    }

    val faBaseType = when (baseType) {
        "Land" -> "زمینی (Land)"
        "Air" -> "هوایی (Air)"
        else -> "دریایی (Sea)"
    }
    story += "🌍 نوع قبیله: $faBaseType\n🚛 شغل قبیله: $packJob\n"

    // ۴. تو شخصاً برای قبیله‌ات چه کار می‌کنی؟ (1d6)
    val roleInPack = when (DiceSource.rollOne(6, "Lifepath — جدول d6")) {
        1 -> "پیشاهنگ و مذاکره‌کننده (Scout)"
        2 -> "محافظ کاروان و مسئول تسلیحات (Outrider)"
        3 -> "خلبان یا راننده ترابری (Transport pilot/driver)"
        4 -> "مسئول بارگیری و جابه‌جایی محموله‌های سنگین (Loadmaster)"
        5 -> "قاچاقچیِ انفرادی (Solo smuggler)"
        6 -> "مسئول تدارکات و تامین سوخت/وسایل نقلیه (Procurement)"
        else -> "نامشخص"
    }
    story += "🛠️ وظیفه تو در قبیله: $roleInPack\n"

    // ۵. فلسفه‌ی کلی قبیله‌ی شما چیست؟ (1d6)
    val philosophy = when (DiceSource.rollOne(6, "Lifepath — جدول d6")) {
        1 -> "همیشه برای خیر کار می‌کند؛ بقیه را می‌پذیرد و فقط می‌خواهد در صلح زندگی کند."
        2 -> "بیشتر شبیه یک تجارت خانوادگی است و به عنوان یک کسب‌وکار عادلانه و صادق عمل می‌کند."
        3 -> "گاهی اوقات می‌لغزد و کارهای غیراخلاقی می‌کند، اما نادر است."
        4 -> "حاضر است برای به دست آوردن نیازهای قبیله، هر قانونی را دور بزند."
        5 -> "بی‌رحم و خودمحور؛ حاضر است برای پیشرفت قبیله کارهای بدی انجام دهد."
        6 -> "کاملاً شرور! در جاده‌ها می‌تازید، می‌کشید، غارت می‌کنید و باعث وحشت همه می‌شوید."
        else -> "نامشخص"
    }
    story += "⚖️ فلسفه قبیله: $philosophy\n"

    // ۶. چه کسی دنبال نابودی قبیله شماست؟ (1d6)
    val gunning = when (DiceSource.rollOne(6, "Lifepath — جدول d6")) {
        1 -> "جرایم سازمان‌یافته / مافیا (Organized Crime)"
        2 -> "بوسترگنگ‌ها (Boostergangs)"
        3 -> "قاچاقچیان مواد مخدر (Drug Runners)"
        4 -> "سیاستمداران کثیف (Dirty Politicians)"
        5 -> "قبیله‌های رقیب که در بیزینس شما دخالت می‌کنند."
        6 -> "پلیس‌های کثیف و فاسد (Dirty Cops)"
        else -> "نامشخص"
    }
    story += "🎯 دشمنان قبیله: $gunning"

    return story
}}
