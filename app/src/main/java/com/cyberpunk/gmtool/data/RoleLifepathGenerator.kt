            5 -> "شریک مخفی با ارتباطات گنگی و مافیایی"
            6 -> "شریک مخفی با ارتباطات شرکتی (Corporate)"
            else -> "نامشخص"
        }
        story += "👥 وضعیت کاری: تیمی کار می‌کنی.\n👤 هویت شریک: $partner\n"
    } else {
