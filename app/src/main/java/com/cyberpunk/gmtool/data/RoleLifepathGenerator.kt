    fun generateForRole(roleName: String): String {
        return when (roleName.lowercase().trim()) {
            "solo", "سولو" -> generateSolo()
            "rockerboy", "راکربوی" -> generateRockerboy()
            "netrunner", "نترانر", "نت رانر" -> generateNetrunner()
            "tech", "تک", "تکنسین" -> generateTech()
            "medtech", "مدتک", "مد تک", "پزشک" -> generateMedtech()
            "media", "مدیا", "رسانه", "خبرنگار" -> generateMedia()
            "exec", "اگزک", "مدیر", "مدیر شرکتی" -> generateExec()
            "lawman", "لاومن", "پلیس", "مامور قانون" -> generateLawman()
            "fixer", "فیکسر", "دلال", "واسطه" -> generateFixer()
            "nomad", "نومد", "کوچ‌نشین" -> generateNomad() // <--- این خط اضافه شد (نقش آخر!)
            else -> "هنوز مسیر زندگی اختصاصی برای نقش '$roleName' به دیتابیس اضافه نشده!"
        }
    }

