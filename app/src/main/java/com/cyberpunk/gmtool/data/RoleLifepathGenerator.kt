        2 -> "یک غرفه (Booth) در یک بارِ محلی."
        3 -> "فقط از طریق پیام‌های دیتاپول (Data Pool) و قرارهای مخفیانه (Dead drops) کار می‌کنی."
        4 -> "یک اتاق اضافه در یک انبار، مغازه، یا کلینیک."
        5 -> "یک ساختمانِ متروکه."
        6 -> "لابیِ یک هتلِ کپسولی (Cube hotel)."
        else -> "نامشخص"
    }
    story += "🏢 دفتر کار: $office\n"

    // ۴. مشتریان جانبی‌ات چه کسانی هستند؟ (1d6)
    val clients = when (DiceSource.rollOne(6, "Lifepath — جدول d6")) {
        1 -> "راکربوی‌ها یا خبرنگاران محلی که از تو می‌خواهند برایشان اجرا یا رابط جور کنی."
